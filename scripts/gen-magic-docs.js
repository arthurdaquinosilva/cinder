#!/usr/bin/env node
// Write docs/magics.md from the magic registry. `--check` exits 1 when the file is out of date (CI).

import fs from 'node:fs';
import { CATEGORIES, CELL_MAGICS, LINE_MAGICS } from '../src/magics/index.js';

const target = new URL('../docs/magics.md', import.meta.url);

function render() {
  const out = ['# Magic reference', '', '<!-- Generated by scripts/gen-magic-docs.js — edit the docs in src/magics/ instead. -->', ''];
  out.push('Line magics start a line with `%`; cell magics start a cell with `%%` and take the rest of the cell as input.');
  out.push('Magic lines can also be mixed into JavaScript cells. `%help name` shows the same text inside cinder.', '');
  const groups = {};
  for (const spec of [...Object.values(LINE_MAGICS), ...Object.values(CELL_MAGICS)]) (groups[spec.category] ??= []).push(spec);
  for (const [key, label] of Object.entries(CATEGORIES)) {
    const specs = groups[key];
    if (!specs) continue;
    out.push(`## ${label[0].toUpperCase()}${label.slice(1)}`, '');
    const primary = specs.filter((s) => !s.aliasOf);
    for (const s of primary) {
      const prefix = s.kind === 'cell' ? '%%' : '%';
      const aliases = specs.filter((a) => a.aliasOf === s.name && a.kind === s.kind).map((a) => `\`${prefix}${a.name}\``);
      out.push(`### \`${prefix}${s.name}${s.usage ? ' ' + s.usage : ''}\``, '');
      out.push(s.doc + (aliases.length ? ` Also: ${aliases.join(', ')}.` : ''), '');
    }
  }
  return out.join('\n').trimEnd() + '\n';
}

const text = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('docs/magics.md is out of date — run: npm run docs');
    process.exit(1);
  }
  console.log('docs/magics.md is up to date');
} else {
  fs.writeFileSync(target, text);
  console.log(`wrote docs/magics.md (${Object.keys(LINE_MAGICS).length} line magics, ${Object.keys(CELL_MAGICS).length} cell magics)`);
}
